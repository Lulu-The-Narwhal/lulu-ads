#!/usr/bin/env node
/**
 * Extracts FRAME_HTML from python/lulu_ads/widgets.py and emits
 * js/src/resultFrame.ts, keeping the result-widget frame byte-identical
 * across the two SDKs (same job sync-widget-bundle.sh does for the
 * sponsored-card bundle). Run after editing the frame in widgets.py.
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const py = readFileSync(resolve(root, "python/lulu_ads/widgets.py"), "utf8");

const m = py.match(/FRAME_HTML = r"""([\s\S]*?)"""\n\n\ndef /);
if (!m) {
  console.error("sync-result-frame: FRAME_HTML block not found in widgets.py");
  process.exit(1);
}
const frame = m[1];

const out = `/**
 * GENERATED by scripts/sync-result-frame.mjs from python/lulu_ads/widgets.py
 * -- do not edit by hand; edit the frame there and re-run the script.
 */
// prettier-ignore
export const RESULT_FRAME_HTML: string = ${JSON.stringify(frame)};
`;
writeFileSync(resolve(root, "js/src/resultFrame.ts"), out);
console.log(`sync-result-frame: wrote js/src/resultFrame.ts (${frame.length} chars)`);
